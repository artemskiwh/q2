// Downloads brand logos from Clearbit and writes lib/brand-logos.ts.
// Runs in GitHub Actions (has internet) — the sandbox doesn't.

import { writeFile, mkdir, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "public", "assets", "logos");
const MAP_FILE = path.join(ROOT, "lib", "brand-logos.ts");

// Brand -> ordered list of candidate domains. First one that returns a valid image wins.
const BRANDS = {
  ELFBAR: ["elfbar.com", "elfbarvape.com"],
  GEEKBAR: ["geekbarvape.com", "geekbar.com"],
  "GEEK VAPE": ["geekvape.com"],
  VAPORESSO: ["vaporesso.com"],
  VOZOL: ["vozol.com", "vozolworld.com"],
  WAKA: ["wakavapor.com", "wakavape.com"],
  PUFFMI: ["puffmi.com", "puffmivape.com"],
  "BUBBLE MON": ["bubble-mon.com", "bubblemon.com"],
  DUALL: ["duallvape.com", "duall.com"],
  FIZZY: ["fizzyvape.com", "fizzyworld.com", "fizzyjuice.com"],
  LAISKA: ["laiska.shop", "laiska.com"],
};

const brandToSlug = (brand) =>
  brand.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function tryClearbit(domain) {
  const url = `https://logo.clearbit.com/${domain}?size=512&format=png`;
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) return null;
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 200) return null;
  return buf;
}

async function fetchBrand(brand, domains) {
  for (const d of domains) {
    try {
      const buf = await tryClearbit(d);
      if (buf) {
        console.log(`  ${brand} <- ${d} (${(buf.length / 1024).toFixed(1)} KB)`);
        return buf;
      }
    } catch (e) {
      console.log(`  ${brand} ${d} error: ${e.message}`);
    }
  }
  return null;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const mapping = {};
  console.log("Fetching brand logos from Clearbit:");

  for (const [brand, domains] of Object.entries(BRANDS)) {
    const slug = brandToSlug(brand);
    const outPath = path.join(OUT_DIR, `${slug}.png`);
    const publicPath = `/assets/logos/${slug}.png`;

    if (existsSync(outPath) && !process.argv.includes("--force")) {
      console.log(`  ${brand} (cached)`);
      mapping[brand] = publicPath;
      continue;
    }

    const buf = await fetchBrand(brand, domains);
    if (buf) {
      await writeFile(outPath, buf);
      mapping[brand] = publicPath;
    } else {
      console.log(`  ${brand} — no logo found, skipping`);
    }
  }

  const tsBody = `// Auto-generated by scripts/fetch-brand-logos.mjs — do not edit by hand.
// Maps brand name (as in products.ts) -> /public/ relative path to logo.

export const BRAND_LOGOS: Record<string, string> = ${JSON.stringify(mapping, null, 2)};
`;
  await writeFile(MAP_FILE, tsBody);
  console.log(`\nWrote ${Object.keys(mapping).length} brands to ${MAP_FILE}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
