#!/usr/bin/env node
/**
 * Fetches product photos from Unsplash and saves them under public/products/.
 * Also writes lib/product-images.ts (slug -> path map) so ProductVisual can
 * prefer the real photo over the generated SVG.
 *
 * Requires env: UNSPLASH_ACCESS_KEY  (https://unsplash.com/developers)
 *
 * Run locally:   UNSPLASH_ACCESS_KEY=xxx node scripts/fetch-product-images.mjs
 * In CI:         see .github/workflows/fetch-product-images.yml
 */

import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT_DIR = join(ROOT, "public", "products");
const MAP_FILE = join(ROOT, "lib", "product-images.ts");

const ACCESS_KEY = process.env.UNSPLASH_ACCESS_KEY;
if (!ACCESS_KEY) {
  console.error("ERROR: UNSPLASH_ACCESS_KEY env var is required.");
  process.exit(1);
}

const FORCE = process.argv.includes("--force");

// Per-product search query overrides. Anything not in the map gets a query
// derived from category + brand. Keeping queries generic so Unsplash returns
// matching stock photos.
const QUERY_OVERRIDES = {
  "fizzy-great-10000": "colorful vape device pink",
  "elfbar-monnight-25000": "elf bar disposable vape",
  "geekbar-32000": "geek bar disposable vape",
  "geekbar-40000": "geek bar disposable vape blue",
  "geekbar-50000": "geek bar disposable vape orange",
  "vozol-shisha-25000": "vozol vape device",
  "waka-8000": "waka vape disposable",
  "waka-20000": "waka vape device purple",
  "waka-25000": "waka vape device",
  "waka-60000": "waka vape disposable",
  "duall-salt": "vape salt nicotine device",
  "bubble-mon-30000": "korean vape disposable",
  "puffmi-pure-12000": "compact disposable vape",
  "laiska-queen-10000": "vape device yellow",
};

const CATEGORY_FALLBACK = {
  disposable: "disposable vape device",
  pod: "vape pod system black",
  cartridge: "vape cartridge replacement",
  sale: "vape device sale",
  liquid: "e-liquid bottle vape",
  accessory: "vape charger usb-c",
};

async function loadProducts() {
  // Parse lib/products.ts using a regex – avoids pulling in a TS toolchain.
  // We only need slug + brand + category.
  const src = await import("node:fs").then((m) =>
    m.promises.readFile(join(ROOT, "lib", "products.ts"), "utf8"),
  );
  const items = [];
  const re =
    /\{\s*slug:\s*"([^"]+)",\s*brand:\s*"([^"]+)",\s*name:\s*"[^"]+",\s*category:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    items.push({ slug: m[1], brand: m[2], category: m[3] });
  }
  return items;
}

function buildQuery(product) {
  if (QUERY_OVERRIDES[product.slug]) return QUERY_OVERRIDES[product.slug];
  const cat = CATEGORY_FALLBACK[product.category] ?? "vape device";
  return `${product.brand.toLowerCase()} ${cat}`;
}

async function searchUnsplash(query, seen) {
  const url = new URL("https://api.unsplash.com/search/photos");
  url.searchParams.set("query", query);
  url.searchParams.set("orientation", "portrait");
  url.searchParams.set("per_page", "10");
  url.searchParams.set("content_filter", "high");
  const res = await fetch(url, {
    headers: { Authorization: `Client-ID ${ACCESS_KEY}` },
  });
  if (!res.ok) {
    throw new Error(`Unsplash search failed ${res.status} ${res.statusText} for "${query}"`);
  }
  const json = await res.json();
  // Prefer first result not seen yet to avoid duplicate photos across cards.
  for (const p of json.results) {
    if (!seen.has(p.id)) return p;
  }
  return json.results[0] ?? null;
}

async function downloadTo(url, file) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(file, buf);
  return buf.length;
}

function tsMap(entries) {
  const body = entries
    .map(([slug, path]) => `  "${slug}": "${path}",`)
    .join("\n");
  return `// Auto-generated by scripts/fetch-product-images.mjs — do not edit by hand.\n// Maps product slug -> path under /public/ for the real product photo.\n// Empty map means SVG fallbacks will be used.\n\nexport const PRODUCT_IMAGES: Record<string, string> = {\n${body}\n};\n`;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const products = await loadProducts();
  console.log(`Loaded ${products.length} products`);

  const seen = new Set();
  const map = {};
  let downloaded = 0;
  let skipped = 0;
  let failed = 0;

  for (const p of products) {
    const target = join(OUT_DIR, `${p.slug}.jpg`);
    const publicPath = `/products/${p.slug}.jpg`;

    if (!FORCE && existsSync(target)) {
      map[p.slug] = publicPath;
      skipped++;
      console.log(`[skip] ${p.slug} (already exists)`);
      continue;
    }

    const query = buildQuery(p);
    try {
      const photo = await searchUnsplash(query, seen);
      if (!photo) {
        console.warn(`[miss] ${p.slug} — no results for "${query}"`);
        failed++;
        continue;
      }
      seen.add(photo.id);
      const bytes = await downloadTo(photo.urls.regular, target);
      map[p.slug] = publicPath;
      downloaded++;
      console.log(
        `[ok]   ${p.slug} <- ${photo.id} by ${photo.user?.name ?? "?"} (${(bytes / 1024).toFixed(0)} KB)`,
      );
    } catch (err) {
      console.error(`[fail] ${p.slug}: ${err.message}`);
      failed++;
    }
  }

  const entries = Object.entries(map).sort((a, b) => a[0].localeCompare(b[0]));
  await writeFile(MAP_FILE, tsMap(entries));

  console.log(
    `\nDone. downloaded=${downloaded} skipped=${skipped} failed=${failed} total=${products.length}`,
  );
  console.log(`Map written to ${MAP_FILE}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
